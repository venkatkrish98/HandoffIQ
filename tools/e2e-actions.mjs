import { attach, frameOf } from './lib.mjs';
const { b, pg } = await attach();
const fr = frameOf(pg) || pg.frames().find((f) => f !== pg.mainFrame());
const log = (...a) => console.log(...a);
await fr.getByRole('tab', { name: /Actions/ }).click(); await pg.waitForTimeout(800);
await fr.getByRole('button', { name: /Propose Jira tasks/ }).click();
await fr.waitForSelector('text=Review & approve'); await pg.waitForTimeout(1200);
log((await fr.locator('#main').innerText()).slice(0, 1200));
await fr.getByRole('button', { name: /Review & approve/ }).click(); await pg.waitForTimeout(900);
await fr.getByRole('combobox', { name: 'Create Jira issues in project', exact: true }).click(); await pg.waitForTimeout(400);
await fr.getByRole('option', { name: /Customer Onboarding/ }).first().click(); await pg.waitForTimeout(400);
await fr.getByRole('combobox', { name: 'Create Confluence page in space' }).click(); await pg.waitForTimeout(600);
log('SPACES', await fr.getByRole('option').allInnerTexts());
await fr.getByRole('option', { name: /Software Development/ }).click(); await pg.waitForTimeout(400);
await fr.getByLabel('I reviewed these changes').check(); await pg.waitForTimeout(800);
await fr.getByRole('button', { name: /Approve & create/ }).click();
await fr.waitForSelector('text=/item\(s\) created|created, |failed/', { timeout: 150000 }).catch(() => {});
await pg.waitForTimeout(2000);
log('--- RESULT ---'); log((await fr.locator('#main').innerText()).slice(0, 1800));
await pg.screenshot({ path: 'out-app.png' });
await b.close();
