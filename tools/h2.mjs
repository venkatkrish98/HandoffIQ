await fr.getByRole('button', { name: /Expected delivery date/ }).click(); await wait(400);
await fr.getByRole('button', { name: 'Next month' }).click(); await fr.getByRole('button', { name: 'Next month' }).click(); await wait(300);
await fr.locator('[data-date="2027-02-03"]').click();
await fr.getByRole('button', { name: 'Continue' }).click(); await wait(2500);
await fr.getByLabel(/Specific Jira issues/).fill('KAN-77, KAN-78, KAN-79');
